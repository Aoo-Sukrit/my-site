-- ============================================================================
--  1. เพิ่ม constraint แบบ NOT VALID
-- ----------------------------------------------------------------------------
--  NOT VALID คือหัวใจของไฟล์นี้
--
--  ปกติตอนเพิ่ม check constraint Postgres จะไล่ตรวจทุกแถวที่มีอยู่ก่อน
--  ถ้ามีแถวไหนผิดกฎ คำสั่งทั้งอันจะล้มทันที แถวทดสอบเดือนกันยาที่กรอกไว้
--  0.01 กม. จะทำให้เพิ่ม constraint นี้ไม่ได้เลย
--
--  NOT VALID บอกให้ข้ามการตรวจแถวเก่าไป แต่ยังบังคับกับทุก insert และ update
--  ที่เกิดหลังจากนี้ตามปกติ ซึ่งตรงกับที่ต้องการคือ
--  ข้อมูลเก่าอยู่ต่อได้ ของใหม่ต้องเข้ากติกา
--
--  ข้อควรรู้: แถวเก่าที่ผิดกฎจะแก้ไม่ได้อีกแล้ว เพราะการ update จะถูกตรวจด้วย
--  ถ้าจะแก้แถวพวกนั้นต้องใส่ค่าที่เข้ากติกาใหม่ไปเลย หรือลบทิ้ง
--
--  constraint เดิม distance_km > 0 จาก 003_runs.sql ปล่อยไว้ตามเดิม
--  ไม่ขัดกัน เพราะกติกาใหม่เข้มกว่าอยู่แล้ว
-- ============================================================================

alter table public.runs drop constraint if exists runs_distance_range;

alter table public.runs
  add constraint runs_distance_range
  check (distance_km >= 0.50 and distance_km <= 200.00)
  not valid;

comment on constraint runs_distance_range on public.runs is
  'ระยะต่อหนึ่งรายการ 0.50 ถึง 200.00 กม. เพิ่มแบบ NOT VALID '
  'เพื่อให้ข้อมูลทดสอบเดือนกันยาที่ต่ำกว่าขั้นต่ำยังอยู่ได้';


