export const CROP_ASPECT_LABEL = (() => {
  for (let down = 1; down <= 20; down++) {
    const across = Math.round(CROP_ASPECT * down);
    if (Math.abs(across / down - CROP_ASPECT) < 1e-9) return `${across}:${down}`;
  }
  return CROP_ASPECT.toFixed(2);
})();
